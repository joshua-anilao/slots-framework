/**
 * sync:cocos. Cocos Creator can only import code inside `assets/`, so the shared packages are COPIED into
 * `client-cocos/assets/shared/`. The copy is generated: never edit it, edit `packages/*` and run `npm run sync:cocos`.
 *
 * Usage:
 *   npm run sync:cocos          write the copy
 *   npm run check:cocos         fail (exit 1) if the copy is missing, stale or has stray files
 *
 * Imports of the workspace names ("@slots/math-core") become relative paths, because Cocos cannot resolve them.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

/** One shared package: where it comes from and where it lands (paths relative to the repo root, with "/"). */
export interface SyncTarget { name: string; from: string; to: string }

export const TARGETS: SyncTarget[] = [
  { name: '@slots/math-core', from: 'packages/math-core/src', to: 'client-cocos/assets/shared/math-core' },
  { name: '@slots/game-logic', from: 'packages/game-logic/src', to: 'client-cocos/assets/shared/game-logic' },
];

export const MANIFEST = 'client-cocos/sync-manifest.json';
const HEADER = (src: string) => `// GENERATED by "npm run sync:cocos" from ${src}. Do not edit here.\n`;

const walk = (dir: string): string[] =>
  readdirSync(dir).flatMap(n => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

/** Builds the full expected output: every generated file with its text, plus the manifest. Writes nothing. */
export function buildOutput(root: string, targets: SyncTarget[] = TARGETS): Map<string, string> {
  const out = new Map<string, string>();
  const entryOf = new Map(targets.map(t => [t.name, t.to + '/index.ts']));
  for (const t of targets) {
    const srcDir = join(root, t.from);
    for (const file of walk(srcDir).sort()) {
      if (!file.endsWith('.ts')) continue;
      const rel = relative(srcDir, file).split(sep).join('/');
      const dest = `${t.to}/${rel}`;
      let text = readFileSync(file, 'utf8');
      // "@slots/x" -> relative path to the copied index of that package.
      text = text.replace(/(from\s+|import\s*\()(['"])(@slots\/[a-z-]+)\2/g, (m, pre: string, q: string, pkg: string) => {
        const entry = entryOf.get(pkg);
        if (!entry) throw new Error(`${t.from}/${rel} imports ${pkg}, which is not a synced package`);
        let r = posix.relative(posix.dirname(dest), entry).replace(/\.ts$/, '');
        if (!r.startsWith('.')) r = './' + r;
        return `${pre}${q}${r}${q}`;
      });
      out.set(dest, HEADER(`${t.from}/${rel}`) + text);
    }
  }
  const hash = createHash('sha1');
  for (const [p, text] of out) hash.update(p).update('\0').update(text).update('\0');
  out.set(MANIFEST, JSON.stringify({ note: 'Generated by sync:cocos', files: out.size, sha1: hash.digest('hex') }, null, 2) + '\n');
  return out;
}

/** Files that exist in the generated folders but are not part of the expected output (stale or hand-added). */
function strayFiles(root: string, expected: Map<string, string>, targets: SyncTarget[]): string[] {
  const stray: string[] = [];
  for (const t of targets) {
    const dir = join(root, t.to);
    if (!existsSync(dir)) continue;
    for (const f of walk(dir)) {
      const rel = relative(root, f).split(sep).join('/');
      // Cocos Creator adds .meta files next to every asset; they are not stray.
      if (rel.endsWith('.meta')) continue;
      if (!expected.has(rel)) stray.push(rel);
    }
  }
  return stray;
}

export function writeSync(root: string, targets: SyncTarget[] = TARGETS): { written: number } {
  const expected = buildOutput(root, targets);
  for (const t of targets) {
    const dir = join(root, t.to);
    if (existsSync(dir)) for (const f of walk(dir)) if (!f.endsWith('.meta') && !expected.has(relative(root, f).split(sep).join('/'))) rmSync(f);
  }
  let written = 0;
  for (const [rel, text] of expected) {
    const file = join(root, rel);
    if (existsSync(file) && readFileSync(file, 'utf8') === text) continue;
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
    written++;
  }
  return { written };
}

/** Returns the list of problems (empty when the copy is up to date). */
export function checkSync(root: string, targets: SyncTarget[] = TARGETS): string[] {
  const expected = buildOutput(root, targets);
  const problems: string[] = [];
  for (const [rel, text] of expected) {
    const file = join(root, rel);
    if (!existsSync(file)) problems.push(`missing: ${rel}`);
    else if (readFileSync(file, 'utf8') !== text) problems.push(`stale: ${rel}`);
  }
  for (const rel of strayFiles(root, expected, targets)) problems.push(`stray: ${rel}`);
  return problems;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  if (process.argv.includes('--check')) {
    const problems = checkSync(root);
    if (problems.length) {
      console.error(`client-cocos/assets/shared is out of date (${problems.length} problem(s)):\n  ${problems.slice(0, 20).join('\n  ')}\nRun: npm run sync:cocos`);
      process.exit(1);
    }
    console.log('client-cocos/assets/shared is up to date.');
  } else {
    const { written } = writeSync(root);
    console.log(`sync:cocos done: ${written} file(s) written.`);
  }
}
